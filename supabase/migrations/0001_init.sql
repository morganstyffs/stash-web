-- ---------------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'wallets','categories','stock_items','transactions','stock_sales','favorites','recurring'
  ]
  loop
    execute format('drop trigger if exists set_updated_at on public.%I;', t);
    execute format(
      'create trigger set_updated_at before update on public.%I
       for each row execute function public.set_updated_at();', t);
  end loop;
end $$;

-- ===========================================================================
-- Row Level Security — enable + owner-only policies on EVERY table.
-- (RLS is likely already enabled by automatic RLS; enabling again is a no-op.)
-- Policies scope every row to its owner via auth.uid() = user_id, and are
-- granted only to the `authenticated` role (anon has no access).
-- ===========================================================================
do $$
declare t text;
begin
  foreach t in array array[
    'wallets','categories','stock_items','transactions','stock_sales','favorites','recurring'
  ]
  loop
    execute format('alter table public.%I enable row level security;', t);

    execute format('drop policy if exists %1$I on public.%2$I;', t || '_select_own', t);
    execute format(
      'create policy %1$I on public.%2$I for select to authenticated
         using (auth.uid() = user_id);', t || '_select_own', t);

    execute format('drop policy if exists %1$I on public.%2$I;', t || '_insert_own', t);
    execute format(
      'create policy %1$I on public.%2$I for insert to authenticated
         with check (auth.uid() = user_id);', t || '_insert_own', t);

    execute format('drop policy if exists %1$I on public.%2$I;', t || '_update_own', t);
    execute format(
      'create policy %1$I on public.%2$I for update to authenticated
         using (auth.uid() = user_id) with check (auth.uid() = user_id);', t || '_update_own', t);

    execute format('drop policy if exists %1$I on public.%2$I;', t || '_delete_own', t);
    execute format(
      'create policy %1$I on public.%2$I for delete to authenticated
         using (auth.uid() = user_id);', t || '_delete_own', t);
  end loop;
end $$;
